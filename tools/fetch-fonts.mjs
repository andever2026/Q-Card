// Copies the fonts the public site uses from Google Fonts into fonts/, so visitors' browsers never contact Google
// for them. Run: node tools/fetch-fonts.mjs (uses curl). Rewrites fonts/fonts.css and fonts/*.woff2; fonts/OFL.txt is
// their licence and stays as it is.
//   Klee One: every slice, for the Japanese on the page (textbook-style shapes). Google splits each weight into
//   ~120 small files by character, and the browser downloads only the ones a page needs.
//   Zen Kaku Gothic New: Latin only, for the interface; Japanese interface text uses the system's Japanese font.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), "../fonts");
// A current browser's user agent, so Google serves woff2 files with unicode-range slices.
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36";
const get = (url, out) => execFileSync("curl", ["-sSfL", "-A", UA, ...(out ? ["-o", out] : []), url], { maxBuffer: 64 << 20 });
const FAMILIES = [
  { q: "Klee+One:wght@400;600", short: "klee", keep: () => true },
  { q: "Zen+Kaku+Gothic+New:wght@400;500;700", short: "zen", keep: (subset) => /^latin(-ext)?$/.test(subset) },
];

fs.mkdirSync(dir, { recursive: true });
for (const f of fs.readdirSync(dir)) if (f.endsWith(".woff2")) fs.rmSync(path.join(dir, f));
let css = "/* Generated by tools/fetch-fonts.mjs from Google Fonts: Klee One and Zen Kaku Gothic New, SIL Open Font License 1.1 (OFL.txt). */\n";
let n = 0;
for (const fam of FAMILIES) {
  const src = get(`https://fonts.googleapis.com/css2?family=${fam.q}&display=swap`).toString();
  for (const [, subset = "", body] of src.matchAll(/(?:\/\*\s*([^*]+?)\s*\*\/\s*)?@font-face\s*\{([^}]*)\}/g)) {
    if (!fam.keep(subset)) continue;
    const family = body.match(/font-family:\s*'([^']+)'/)[1], weight = body.match(/font-weight:\s*(\d+)/)[1];
    const url = body.match(/url\(([^)]+)\)/)[1], range = body.match(/unicode-range:\s*([^;]+);/)[1].replace(/\s+/g, "");
    // Named subsets (latin, cyrillic, …) carry a comment; the numbered Japanese slices only have the number in their URL.
    const name = `${fam.short}-${weight}-${subset.replace(/[^a-z0-9-]/gi, "") || url.match(/\.(\d+)\.woff2$/)[1]}.woff2`;
    get(url, path.join(dir, name));
    css += `@font-face{font-family:'${family}';font-weight:${weight};font-display:swap;src:url(${name}) format('woff2');unicode-range:${range}}\n`;
    n++;
  }
}
fs.writeFileSync(path.join(dir, "fonts.css"), css);
console.log(`Wrote fonts/fonts.css and ${n} font files.`);
